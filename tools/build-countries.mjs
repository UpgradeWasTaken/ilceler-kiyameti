// Builds js/countries.js: every sovereign or de facto country with its Turkish name.
// Source: Natural Earth admin-0 (public domain), cached by build-map.mjs, plus de facto
// states Natural Earth folds into others.
//   cd tools && node build-countries.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(HERE, '.cache', 'countries.geojson');
const OUT = path.join(HERE, '..', 'js', 'countries.js');

// Codes for units without an ISO code, and names this game uses on purpose.
const CODE_BY_ADM0 = { CYN: 'KKTC', SOL: 'XSL', KOS: 'XK' };
const NAME_OVERRIDES = {
  TR: 'Türkiye', CY: 'GKRY', KKTC: 'KKTC', XSL: 'Somaliland', CZ: 'Çekya', TW: 'Tayvan', CN: 'Çin',
  BY: 'Belarus', ZA: 'Güney Afrika',
};
const EXTRA = { XAB: 'Abhazya', XSO: 'Güney Osetya', XTD: 'Transdinyester' };
const FULL_NAMES = { KKTC: 'Kuzey Kıbrıs Türk Cumhuriyeti', CY: 'Güney Kıbrıs Rum Yönetimi' };
const SKIP = new Set(['ATA', 'BJN', 'BRT', 'CNM', 'KAS', 'PGA', 'SCR', 'SER', 'SPI', 'BRI', 'USG', 'KAB']);

const fc = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const out = {};
for (const { properties: p } of fc.features) {
  if (SKIP.has(p.ADM0_A3)) continue;
  const sovereign = p.TYPE === 'Sovereign country' || p.TYPE === 'Sovereignty' || (p.TYPE === 'Country' && p.ADMIN === p.SOVEREIGNT) ||
    (p.TYPE === 'Disputed' && p.ADMIN === p.SOVEREIGNT) || ['SAH', 'PSX'].includes(p.ADM0_A3);
  if (!sovereign) continue;
  const code = CODE_BY_ADM0[p.ADM0_A3] || (p.ISO_A2_EH !== '-99' ? p.ISO_A2_EH : null);
  if (!code) { console.warn('no code for', p.ADMIN); continue; }
  out[code] = NAME_OVERRIDES[code] || p.NAME_TR;
}
Object.assign(out, EXTRA);
const collator = new Intl.Collator('tr');
const sorted = Object.fromEntries(Object.entries(out).sort((a, b) => collator.compare(a[1], b[1])));
fs.writeFileSync(OUT, `// Generated by tools/build-countries.mjs (Natural Earth, public domain, + de facto states).
// Keys are ISO 3166-1 alpha-2 codes where one exists; KKTC and X… codes otherwise.
export const COUNTRIES = ${JSON.stringify(sorted, null, 0).replace(/","/g, '",\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, ',\n}')};

export const COUNTRY_FULL_NAMES = ${JSON.stringify(FULL_NAMES)};
`);
console.log(`${Object.keys(sorted).length} countries → ${OUT}`);
